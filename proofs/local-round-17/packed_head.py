"""Exact verification below a given width, without external dependencies.

Usage: python packed_head.py A B THRESHOLD (2 <= A < B).
Return counts of all admissible widths and of those requiring direct expansion.

For rectangles of the same area N and smaller sides s < t <= sqrt(N),
Gangl–Gutiérrez–Szwej, Corollaries 1.5–1.6, establish the required comparison
if s divides t or N/t (https://arxiv.org/abs/2507.06220). Comparisons add,
so any directed path from a to b that uses these divisibility edges suffices.
The path check depends only on that published theorem and integer arithmetic.

For each remaining width c let J = floor(b*c/2). To check first differences
through J inclusive, evaluate the series at B = 2^bits modulo B^(J+1).
Evaluation gives a ring map from Z[q]/(q^(J+1)) into Z/(B^(J+1)).
For a rectangle (h,w), its first differences are generated by

    prod_(i=1)^h (1-q^(w+i)) / prod_(i=2)^h (1-q^i).

Compute each denominator inverse by successive geometric doublings:
the product of (1+q^(2^k i)), for k=0 up to 2^(k+1) i > J,
equals 1/(1-q^i) modulo q^(J+1). Each numerator factor then takes one
shift and subtraction. The operations may produce carries between radix
digits internally; working in the stated quotient ring makes them harmless.

The final coefficient e_j is the difference of two rectangle first
differences. Its absolute value is <= binom(b+c,b)+binom(a+d,a),
where d=b*c/a, since all rectangle coefficients are nonnegative and sum
to the corresponding ordinary binomial coefficient. The chosen radix
satisfies |e_j| < B/2 uniformly over the widths checked in one batch.
Adding B/2 to EVERY digit therefore writes exactly e_j+B/2 in that digit,
with no carries, including for negative e_j. Its high bit is set exactly
when e_j >= 0. A single bit-mask check verifies all ranks from 0 to J.
The original difference has zero constant term and is symmetric about
N/2 by complementation in each rectangle, which completes the proof.
"""
from math import comb
from sys import argv
from time import perf_counter


def has_path(a, b, area):
    reachable = [a]
    for t in range(a+1, b+1):
        if area % t:
            continue
        if any(t % s == 0 or (area//t) % s == 0 for s in reachable):
            reachable.append(t)
    return reachable[-1] == b


def unrestricted(a, b, digitbits, ranks):
    """Values of prod_(i=2)^h 1/(1-q^i) at B mod B^ranks."""
    mask = (1 << (ranks*digitbits)) - 1
    v = 1
    result = {}
    for i in range(2,b+1):
        step = i
        while step < ranks:
            v = (v + (v << (step*digitbits))) & mask
            step *= 2
        if i in (a,b):
            result[i] = v
    return result


def restriction(v, h, w, bits, mask):
    v &= mask
    for i in range(1,h+1):
        v = (v - (v << ((w+i)*bits))) & mask
    return v


def finite(a, b, threshold):
    if not 2 <= a < b:
        raise ValueError("Expected 2 <= a < b.")
    widths=[c for c in range(b,threshold) if (b*c)%a==0]
    check=[c for c in widths if not has_path(a,b,b*c)]
    if not check:
        return len(widths), 0
    cmax = check[-1]
    bound = comb(b+cmax,b) + comb(a+b*cmax//a,a)
    bits = ((bound.bit_length()+1+7)//8)*8
    head = unrestricted(a,b,bits,b*cmax//2+1)
    guard_digit = bytes([0])*(bits//8-1)+bytes([128])
    for c in check:
        ranks = b*c//2+1
        mask = (1 << (ranks*bits))-1
        guard = int.from_bytes(guard_digit*ranks,'little')
        big = restriction(head[b],b,c,bits,mask)
        small = restriction(head[a],a,b*c//a,bits,mask)
        if ((big-small+guard) & guard) != guard:
            raise ArithmeticError((a,b,c))
    return len(widths),len(check)


if __name__ == '__main__':
    a,b,t=map(int,argv[1:])
    start=perf_counter()
    print(a,b,t,finite(a,b,t),round(perf_counter()-start,3))
